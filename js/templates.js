/* NeuroMD — templates.js
   Готовые заготовки для редактора. */
(function () {
  "use strict";

  var Neuro = (window.Neuro = window.Neuro || {});

  var DOC =
    "# Заголовок документа\n\n" +
    "Короткое описание: о чём этот документ и зачем он нужен.\n\n" +
    "## Раздел\n\n" +
    "Обычный текст. Можно выделять **жирным**, *курсивом* и `кодом`.\n\n" +
    "- Первый пункт\n" +
    "- Второй пункт\n" +
    "- Третий пункт\n\n" +
    "## Список задач\n\n" +
    "- [x] Сделано\n" +
    "- [ ] Осталось сделать\n\n" +
    "## Цитата\n\n" +
    "> Хорошая мысль, которую стоит выделить.\n\n" +
    "## Таблица\n\n" +
    "| Понятие | Значение |\n" +
    "| --- | --- |\n" +
    "| Markdown | Текстовый формат |\n" +
    "| Файл | .md |\n\n" +
    "---\n\n" +
    "Готово.\n";

  var README =
    "# Название проекта\n\n" +
    "Одно предложение: что это и какую задачу решает.\n\n" +
    "## Возможности\n\n" +
    "- Возможность один\n" +
    "- Возможность два\n" +
    "- Возможность три\n\n" +
    "## Установка\n\n" +
    "```bash\n" +
    "git clone https://example.com/project.git\n" +
    "cd project\n" +
    "```\n\n" +
    "## Использование\n\n" +
    "```bash\n" +
    "python main.py\n" +
    "```\n\n" +
    "## Структура\n\n" +
    "```text\n" +
    "project/\n" +
    "├── src/\n" +
    "├── tests/\n" +
    "└── README.md\n" +
    "```\n\n" +
    "## Лицензия\n\n" +
    "Укажи лицензию проекта.\n";

  var SKILL =
    "---\n" +
    "name: my-skill\n" +
    "description: Кратко, что делает скилл и когда его применять.\n" +
    "---\n\n" +
    "# My Skill\n\n" +
    "Опиши, какую задачу решает этот скилл и когда его использовать.\n\n" +
    "## Когда использовать\n\n" +
    "- Ситуация первая\n" +
    "- Ситуация вторая\n\n" +
    "## Инструкции\n\n" +
    "1. Шаг первый\n" +
    "2. Шаг второй\n" +
    "3. Шаг третий\n\n" +
    "## Пример\n\n" +
    "```text\n" +
    "Пользователь: сделай X\n" +
    "Агент: выполняет инструкции из этого файла\n" +
    "```\n\n" +
    "## Правила\n\n" +
    "- Всегда проверяй результат перед ответом.\n" +
    "- Никогда не выдумывай данные.\n";

  Neuro.templates = {
    list: [
      { id: "doc", label: "Обычный документ", text: DOC },
      { id: "readme", label: "README проекта", text: README },
      { id: "skill", label: "SKILL.md", text: SKILL }
    ],
    get: function (id) {
      for (var i = 0; i < this.list.length; i++) {
        if (this.list[i].id === id) return this.list[i].text;
      }
      return "";
    }
  };
})();
